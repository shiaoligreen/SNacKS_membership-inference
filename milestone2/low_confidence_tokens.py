import torch
import numpy as np
import pandas as pd
from transformers import AutoTokenizer, AutoModelForCausalLM
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import accuracy_score, f1_score, roc_auc_score
from tqdm.auto import tqdm
from datasets import load_dataset

"""The workflow is:
	1.	tokenize a list of texts with padding=True
	2.	get logits from each model
	3.	shift logits and labels for next-token prediction
	4.	compute token-level cross-entropy with reduction="none"
	5.	mask out padding tokens
	6.	summarize per-example features
	7.	train logistic regression on those features
"""

device = "cuda" if torch.cuda.is_available() else "cpu"
dataset = load_dataset("UBC-SLIME/colx_531_group_project")

# Setup
tokenizer = AutoTokenizer.from_pretrained("UBC-SLIME/colx_531_smollm2-135m")
if tokenizer.pad_token is None:
    tokenizer.pad_token = tokenizer.eos_token

lm1 = AutoModelForCausalLM.from_pretrained("UBC-SLIME/colx_531_smollm2-135m").to(device)
lm2 = AutoModelForCausalLM.from_pretrained("UBC-SLIME/colx_531_smollm2-360m").to(device)

lm1.eval()
lm2.eval()

# Split data into batches
def chunk_list(items, batch_size):
    for i in range(0, len(items), batch_size):
        yield items[i:i + batch_size]

# Compute token level losses for whole batch
import torch.nn.functional as F

def get_batch_token_losses(model, texts, max_length=512):
    encodings = tokenizer(
        texts,
        return_tensors="pt",
        padding=True,
        truncation=True,
        max_length=max_length
    ).to(device)

    input_ids = encodings["input_ids"]
    attention_mask = encodings["attention_mask"]

    with torch.no_grad():
        outputs = model(**encodings)
        logits = outputs.logits

    shift_logits = logits[:, :-1, :]
    shift_labels = input_ids[:, 1:]
    shift_mask = attention_mask[:, 1:]

    token_losses = F.cross_entropy(
        shift_logits.reshape(-1, shift_logits.size(-1)),
        shift_labels.reshape(-1),
        reduction="none"
    ).reshape(shift_labels.size())

    token_losses = token_losses.detach().float().cpu()
    shift_mask = shift_mask.detach().cpu()

    batch_losses = []
    for i in range(token_losses.size(0)):
        valid_losses = token_losses[i][shift_mask[i] == 1].numpy()
        batch_losses.append(valid_losses)

    return batch_losses

# Build low confidence token features
def summarize_token_losses(token_losses, low_conf_frac=0.2):
    token_losses = np.array(token_losses)

    if len(token_losses) == 0:
        return {
            "mean_loss": np.nan,
            "max_loss": np.nan,
            "p90_loss": np.nan,
            "low_conf_mean_loss": np.nan,
            "low_conf_median_loss": np.nan,
            "n_tokens": 0
        }

    k = max(1, int(len(token_losses) * low_conf_frac))
    worst_losses = np.sort(token_losses)[-k:]   # highest loss = lowest confidence

    return {
        "mean_loss": float(np.mean(token_losses)),
        "max_loss": float(np.max(token_losses)),
        "p90_loss": float(np.percentile(token_losses, 90)),
        "low_conf_mean_loss": float(np.mean(worst_losses)),
        "low_conf_median_loss": float(np.median(worst_losses)),
        "n_tokens": int(len(token_losses))
    }

# Create features from both models and their differences
def extract_batch_features(texts, low_conf_frac=0.2, max_length=512):
    losses1_batch = get_batch_token_losses(lm1, texts, max_length=max_length)
    losses2_batch = get_batch_token_losses(lm2, texts, max_length=max_length)

    batch_features = []

    for losses1, losses2 in zip(losses1_batch, losses2_batch):
        s1 = summarize_token_losses(losses1, low_conf_frac=low_conf_frac)
        s2 = summarize_token_losses(losses2, low_conf_frac=low_conf_frac)

        feats = {
            "lm1_mean_loss": s1["mean_loss"],
            "lm1_max_loss": s1["max_loss"],
            "lm1_p90_loss": s1["p90_loss"],
            "lm1_low_conf_mean_loss": s1["low_conf_mean_loss"],
            "lm1_low_conf_median_loss": s1["low_conf_median_loss"],

            "lm2_mean_loss": s2["mean_loss"],
            "lm2_max_loss": s2["max_loss"],
            "lm2_p90_loss": s2["p90_loss"],
            "lm2_low_conf_mean_loss": s2["low_conf_mean_loss"],
            "lm2_low_conf_median_loss": s2["low_conf_median_loss"],

            "diff_mean_loss": s1["mean_loss"] - s2["mean_loss"],
            "diff_max_loss": s1["max_loss"] - s2["max_loss"],
            "diff_p90_loss": s1["p90_loss"] - s2["p90_loss"],
            "diff_low_conf_mean_loss": s1["low_conf_mean_loss"] - s2["low_conf_mean_loss"],
            "diff_low_conf_median_loss": s1["low_conf_median_loss"] - s2["low_conf_median_loss"],

            "n_tokens": s1["n_tokens"]
        }

        batch_features.append(feats)

    return batch_features

# Build feature dataframes in batches
def build_feature_dataframe_batched(hf_dataset, split_name, batch_size=8, low_conf_frac=0.2, max_length=512, max_examples=None):
    rows = []

    n = len(hf_dataset) if max_examples is None else min(len(hf_dataset), max_examples)

    for start in tqdm(range(0, n, batch_size), desc=f"Extracting {split_name}"):
        batch = hf_dataset[start:start + batch_size]

        texts = batch["text"]
        ids = batch["id"]
        labels = batch["is_member"] if "is_member" in batch else None

        batch_features = extract_batch_features(
            texts,
            low_conf_frac=low_conf_frac,
            max_length=max_length
        )

        for i, feats in enumerate(batch_features):
            feats["id"] = ids[i]
            if labels is not None:
                feats["is_member"] = labels[i]
            rows.append(feats)

    return pd.DataFrame(rows)

