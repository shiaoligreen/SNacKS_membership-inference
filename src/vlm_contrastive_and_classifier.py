import io
import os
import random
import argparse
from typing import Dict, List, Optional

import numpy as np
import pandas as pd
import torch
from PIL import Image
from datasets import load_dataset
from sklearn.metrics import roc_auc_score, roc_curve
from tqdm import tqdm
from transformers import AutoProcessor, SmolVLMForConditionalGeneration

MODEL_ID = "UBC-SLIME/colx_585_vlm"
DATASET_ID = "UBC-SLIME/colx585_group_project_data"

def set_seed(seed: int) -> None:
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    if torch.cuda.is_available():
        torch.cuda.manual_seed_all(seed)


def get_device() -> str:
    return "cuda" if torch.cuda.is_available() else "cpu"


def load_image(example: Dict) -> Image.Image:
    if isinstance(example["image"], dict) and "bytes" in example["image"]:
        return Image.open(io.BytesIO(example["image"]["bytes"])).convert("RGB")
    return example["image"].convert("RGB")


def split_text_pair(text: str):
    parts = text.split("\n", 1)
    user_text = parts[0]
    assistant_text = parts[1] if len(parts) > 1 else ""
    return user_text, assistant_text


def build_messages(full_text: str):
    user_text, assistant_text = split_text_pair(full_text)
    messages = [
        {
            "role": "user",
            "content": [
                {"type": "image"},
                {"type": "text", "text": user_text},
            ],
        },
        {
            "role": "assistant",
            "content": [
                {"type": "text", "text": assistant_text},
            ],
        },
    ]
    return messages

def load_model_and_processor(device: str):
    processor = AutoProcessor.from_pretrained(MODEL_ID)
    processor.image_processor.do_image_splitting = False
    processor.image_processor.size = {"longest_edge": 512}
    processor.image_processor.max_image_size = {"longest_edge": 512}

    model = SmolVLMForConditionalGeneration.from_pretrained(
        MODEL_ID,
        torch_dtype=torch.bfloat16 if device == "cuda" else torch.float32,
        _attn_implementation="sdpa",
        trust_remote_code=True,
    ).to(device)

    model.eval()
    return model, processor


def prepare_inputs(image: Image.Image, full_text: str, processor, device: str):
    messages = build_messages(full_text)
    text = processor.apply_chat_template(messages, tokenize=False)
    inputs = processor(text=text, images=[image], return_tensors="pt").to(device)

    if device == "cuda":
        inputs = {
            k: v.to(torch.bfloat16) if v.dtype == torch.float32 else v
            for k, v in inputs.items()
        }

    labels = inputs["input_ids"].clone()
    labels[labels == processor.tokenizer.pad_token_id] = -100
    return inputs, labels

@torch.no_grad()
def compute_pair_loss(image: Image.Image, full_text: str, model, processor, device: str) -> float:
    inputs, labels = prepare_inputs(image, full_text, processor, device)
    outputs = model(**inputs, labels=labels)
    return float(outputs.loss.item())


def load_split(split_name: str, max_examples: Optional[int] = None) -> List[Dict]:
    ds = load_dataset(DATASET_ID, split=split_name)
    records = []

    for example in ds:
        record = {
            "id": example["id"],
            "image": example["image"],
            "text": example["text"],
        }
        if "is_member" in example:
            record["label"] = example["is_member"]
        if "type" in example:
            record["type"] = example["type"]

        records.append(record)

        if max_examples is not None and len(records) >= max_examples:
            break

    return records


def sample_negative_indices(n: int, idx: int, k: int, rng: random.Random) -> List[int]:
    if n <= 1:
        return []

    candidates = list(range(n))
    candidates.remove(idx)

    if k >= len(candidates):
        return candidates

    return rng.sample(candidates, k)

def compute_contrastive_features_for_split(
    records: List[Dict],
    model,
    processor,
    device: str,
    k_caption_neg: int = 5,
    k_image_neg: int = 5,
    seed: int = 42,
) -> pd.DataFrame:
    rng = random.Random(seed)
    n = len(records)
    results = []

    for idx in tqdm(range(n), desc="Computing contrastive features"):
        example = records[idx]

        try:
            image_i = load_image(example)
            text_i = example["text"]

            pos_loss = compute_pair_loss(image_i, text_i, model, processor, device)

            caption_neg_ids = sample_negative_indices(n, idx, k_caption_neg, rng)
            caption_neg_losses = []
            for j in caption_neg_ids:
                text_j = records[j]["text"]
                loss_ij = compute_pair_loss(image_i, text_j, model, processor, device)
                caption_neg_losses.append(loss_ij)

            image_neg_ids = sample_negative_indices(n, idx, k_image_neg, rng)
            image_neg_losses = []
            for j in image_neg_ids:
                image_j = load_image(records[j])
                loss_ji = compute_pair_loss(image_j, text_i, model, processor, device)
                image_neg_losses.append(loss_ji)

            cap_mean = float(np.mean(caption_neg_losses)) if caption_neg_losses else np.nan
            cap_min = float(np.min(caption_neg_losses)) if caption_neg_losses else np.nan
            cap_max = float(np.max(caption_neg_losses)) if caption_neg_losses else np.nan
            cap_std = float(np.std(caption_neg_losses)) if caption_neg_losses else np.nan

            img_mean = float(np.mean(image_neg_losses)) if image_neg_losses else np.nan
            img_min = float(np.min(image_neg_losses)) if image_neg_losses else np.nan
            img_max = float(np.max(image_neg_losses)) if image_neg_losses else np.nan
            img_std = float(np.std(image_neg_losses)) if image_neg_losses else np.nan

            all_neg = caption_neg_losses + image_neg_losses
            all_neg_mean = float(np.mean(all_neg)) if all_neg else np.nan
            all_neg_min = float(np.min(all_neg)) if all_neg else np.nan

            cap_margin_mean = cap_mean - pos_loss if not np.isnan(cap_mean) else np.nan
            img_margin_mean = img_mean - pos_loss if not np.isnan(img_mean) else np.nan
            combined_margin_mean = all_neg_mean - pos_loss if not np.isnan(all_neg_mean) else np.nan

            cap_margin_hard = cap_min - pos_loss if not np.isnan(cap_min) else np.nan
            img_margin_hard = img_min - pos_loss if not np.isnan(img_min) else np.nan
            combined_margin_hard = all_neg_min - pos_loss if not np.isnan(all_neg_min) else np.nan

            #new feature
            all_losses = caption_neg_losses + image_neg_losses + [pos_loss]
            rank = sum(l <= pos_loss for l in all_losses) / len(all_losses)
            rank_score = 1 - rank
            ratio_mean = pos_loss / (1e-6 + all_neg_mean) if not np.isnan(all_neg_mean) else np.nan
            ratio_hard = pos_loss / (1e-6 + all_neg_min) if not np.isnan(all_neg_min) else np.nan
            #
            score = 0.5 * cap_margin_hard + 0.5 * img_margin_hard

            row = {
                "id": example["id"],
                "pos_loss": pos_loss,
                "cap_neg_mean": cap_mean,
                "cap_neg_min": cap_min,
                "cap_neg_max": cap_max,
                "cap_neg_std": cap_std,
                "img_neg_mean": img_mean,
                "img_neg_min": img_min,
                "img_neg_max": img_max,
                "img_neg_std": img_std,
                "cap_margin_mean": cap_margin_mean,
                "img_margin_mean": img_margin_mean,
                "combined_margin_mean": combined_margin_mean,
                "cap_margin_hard": cap_margin_hard,
                "img_margin_hard": img_margin_hard,
                "combined_margin_hard": combined_margin_hard,
                "score": score,
                "rank_score": rank_score,
                "ratio_mean": ratio_mean,
                "ratio_hard": ratio_hard,
            }

            if "label" in example:
                row["label"] = example["label"]
            if "type" in example:
                row["type"] = example["type"]

            results.append(row)

        except Exception as e:
            print(f"Skipped {example['id']} due to error: {e}")

    return pd.DataFrame(results)

def tpr_at_fpr(y_true, y_score, target_fpr: float = 0.1) -> float:
    fpr, tpr, _ = roc_curve(y_true, y_score)
    valid = np.where(fpr <= target_fpr)[0]
    if len(valid) == 0:
        return 0.0
    return float(np.max(tpr[valid]))


def evaluate(df: pd.DataFrame, split_name: str):
    if "label" not in df.columns:
        print(f"{split_name}: no labels available.")
        return

    y_true = df["label"].values
    y_score = df["score"].values

    auc = roc_auc_score(y_true, y_score)
    tpr01 = tpr_at_fpr(y_true, y_score, target_fpr=0.1)

    print(f"[{split_name}] AUC = {auc:.4f} | TPR@FPR=0.1 = {tpr01:.4f}")

